import PDFDocument from "pdfkit";

const BRAND = "#0f766e";
const MUTED = "#64748b";

const fmtDate = (d) => new Date(d).toLocaleDateString("en-IN", { day: "numeric", month: "short", year: "numeric" });
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

// Creates a PDF of one prescription and returns it as a stream (pipe it to the response).
// `rx` must have doctor and patient populated.
export function buildPrescriptionPdf(rx) {
  const doc = new PDFDocument({ size: "A4", margin: 50 });
  const left = 50;
  const width = 495; // page width (595) minus both margins

  // ---- Header ----
  doc.fillColor(BRAND).font("Helvetica-Bold").fontSize(24).text("MediConnect", left, 50);
  doc.fillColor(MUTED).font("Helvetica").fontSize(11).text("Digital Prescription", left, 78);
  doc.fillColor("#000").fontSize(11).text(`Date: ${fmtDate(rx.createdAt)}`, left, 55, { width, align: "right" });
  doc.moveTo(left, 100).lineTo(left + width, 100).strokeColor(BRAND).lineWidth(1.5).stroke();

  // ---- Doctor (left) and patient (right) ----
  const top = 115;
  doc.fillColor(MUTED).fontSize(9).text("DOCTOR", left, top);
  doc.fillColor("#000").font("Helvetica-Bold").fontSize(13).text(rx.doctor?.name || "Not available", left, top + 14);
  doc.font("Helvetica").fontSize(11).fillColor(MUTED).text(rx.doctor?.specialization || "", left, top + 32);

  doc.fillColor(MUTED).fontSize(9).text("PATIENT", 320, top);
  doc.fillColor("#000").font("Helvetica-Bold").fontSize(13).text(rx.patient?.name || "", 320, top + 14);
  doc.font("Helvetica").fontSize(10).fillColor(MUTED);
  doc.text(`Age / Gender: ${rx.patient?.age || "-"} / ${rx.patient?.gender ? cap(rx.patient.gender) : "-"}`, 320, top + 32);
  doc.text("Health ID: ", 320, top + 47, { continued: true });
  doc.font("Courier-Bold").fillColor("#000").text(rx.patient?.healthId || "-");
  doc.font("Helvetica"); // back to the normal font for the rest of the page

  // ---- Diagnosis ----
  let y = 195;
  doc.fillColor(MUTED).fontSize(9).text("DIAGNOSIS", left, y);
  doc.fillColor("#000").font("Helvetica-Bold").fontSize(13).text(rx.diagnosis || "-", left, y + 14, { width });
  y = doc.y + 18;

  // ---- Medicine table ----
  const cols = [
    { title: "Medicine", x: left, w: 150 },
    { title: "Dosage", x: left + 150, w: 80 },
    { title: "When", x: left + 230, w: 90 },
    { title: "Days", x: left + 320, w: 45 },
    { title: "Instructions", x: left + 365, w: 130 },
  ];

  const drawHeader = () => {
    doc.rect(left, y, width, 24).fill(BRAND);
    doc.fillColor("#fff").font("Helvetica-Bold").fontSize(10);
    cols.forEach((c) => doc.text(c.title, c.x + 6, y + 7, { width: c.w - 8 }));
    y += 24;
  };
  drawHeader();

  doc.font("Helvetica").fontSize(10);
  rx.medicines.forEach((m, i) => {
    const cells = [m.name, m.dosage || "-", m.frequency.map(cap).join(", "), String(m.durationDays), m.instructions || "-"];
    const rowH = Math.max(...cells.map((t, k) => doc.heightOfString(t, { width: cols[k].w - 8 }))) + 14;

    if (y + rowH > 760) { doc.addPage(); y = 50; drawHeader(); doc.font("Helvetica").fontSize(10); } // new page if full
    if (i % 2 === 0) doc.rect(left, y, width, rowH).fill("#f1f5f9"); // striped rows
    doc.fillColor("#000");
    cells.forEach((t, k) => doc.text(t, cols[k].x + 6, y + 7, { width: cols[k].w - 8 }));
    y += rowH;
  });

  // ---- Notes and follow-up ----
  y += 18;
  if (rx.notes) {
    doc.fillColor(MUTED).fontSize(9).text("DOCTOR'S NOTES", left, y);
    doc.fillColor("#000").font("Helvetica").fontSize(11).text(rx.notes, left, y + 14, { width });
    y = doc.y + 14;
  }
  if (rx.followUpDate) {
    doc.fillColor(MUTED).fontSize(9).text("FOLLOW-UP DATE", left, y);
    doc.fillColor("#000").font("Helvetica-Bold").fontSize(11).text(fmtDate(rx.followUpDate), left, y + 14);
  }

  // ---- Footer ----
  // The footer is below the bottom margin, so remove the margin first (otherwise pdfkit adds a blank page)
  doc.page.margins.bottom = 0;
  doc.fillColor(MUTED).font("Helvetica").fontSize(9)
    .text("Generated by MediConnect. Take medicines only as advised by your doctor.", left, 790, { width, align: "center", lineBreak: false });

  doc.end();
  return doc;
}
